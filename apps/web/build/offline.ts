import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

/**
 * Makes the build work offline: after Vite writes the app, lists every output file and
 * writes `sw.js`, a service worker that caches them all on install and serves them
 * cache-first. The cache name is a hash of the files, so each build replaces the last.
 */
export function offline(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'nxt-offline',
    apply: 'build',
    configResolved(resolved) {
      config = resolved;
    },
    closeBundle() {
      const outDir = join(config.root, config.build.outDir);
      const files = walk(outDir).filter((f) => !f.endsWith('sw.js') && !f.endsWith('.map'));
      const hash = createHash('sha256');
      for (const file of files) hash.update(file).update(readFileSync(join(outDir, file)));
      const urls = ['./', ...files.map((f) => `./${f}`)];
      const source = SERVICE_WORKER.replace('__VERSION__', hash.digest('hex').slice(0, 12)).replace(
        '__FILES__',
        JSON.stringify(urls),
      );
      writeFileSync(join(outDir, 'sw.js'), source);
    },
  };
}

function walk(dir: string, root = dir): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path, root) : [relative(root, path).split(sep).join('/')];
  });
}

const SERVICE_WORKER = `// Generated by build/offline.ts. Caches the whole app so it runs offline.
const CACHE = 'nxt-web-studio-__VERSION__';
const FILES = __FILES__;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(request, { ignoreSearch: request.mode === 'navigate' });
      if (hit) return hit;
      try {
        return await fetch(request);
      } catch (error) {
        if (request.mode === 'navigate') {
          const shell = await cache.match('./');
          if (shell) return shell;
        }
        throw error;
      }
    }),
  );
});
`;
